#!/usr/bin/env python3
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import sympy as s


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "manuscript" / "generated" / "python_verification.tex"


I2 = s.eye(2)
SIGMA = (
    s.Matrix([[0, 1], [1, 0]]),
    s.Matrix([[0, -s.I], [s.I, 0]]),
    s.Matrix([[1, 0], [0, -1]]),
)


@dataclass
class CheckResult:
    label: str
    verdict: str
    detail: str


def sigma_dot(vec):
    return sum((vec[n] * SIGMA[n] for n in range(3)), s.zeros(2))


def dot(a, b):
    return sum(ai * bi for ai, bi in zip(a, b))


def cross(a, b):
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def mat_paravector(scalar, vec):
    return s.expand(scalar * I2 + sigma_dot(vec))


def scalar_part(mat):
    return s.simplify(s.trace(mat) / 2)


def sigma_coefficients(mat):
    mat = s.Matrix(mat)
    return (
        s.simplify((mat[0, 1] + mat[1, 0]) / 2),
        s.simplify((mat[1, 0] - mat[0, 1]) / (2 * s.I)),
        s.simplify((mat[0, 0] - mat[1, 1]) / 2),
    )


def simplify_matrix(mat):
    return s.Matrix([[s.simplify(s.expand(entry)) for entry in row] for row in mat.tolist()])


def matrix_is_zero(mat):
    return all(s.simplify(s.expand(entry)) == 0 for entry in mat)


def tex(expr):
    return s.latex(s.simplify(s.expand(expr)))


def grad_scalar(expr, x, y, z):
    return (s.diff(expr, x), s.diff(expr, y), s.diff(expr, z))


def div_vector(vec, x, y, z):
    return s.diff(vec[0], x) + s.diff(vec[1], y) + s.diff(vec[2], z)


def curl_vector(vec, x, y, z):
    return (
        s.diff(vec[2], y) - s.diff(vec[1], z),
        s.diff(vec[0], z) - s.diff(vec[2], x),
        s.diff(vec[1], x) - s.diff(vec[0], y),
    )


def E_op(expr, q, V, t):
    return s.I * s.diff(expr, t) - q * V * expr


def P_component(expr, q, A_component, spatial_coord):
    return -s.I * s.diff(expr, spatial_coord) - q * A_component * expr


def E_matrix(mat, q, V, t):
    return s.Matrix(
        [[s.expand(E_op(entry, q, V, t)) for entry in row] for row in mat.tolist()]
    )


def P_component_matrix(mat, q, A_component, spatial_coord):
    return s.Matrix(
        [
            [s.expand(P_component(entry, q, A_component, spatial_coord)) for entry in row]
            for row in mat.tolist()
        ]
    )


def sigma_P(expr, q, Avec, coords):
    x, y, z = coords
    return mat_paravector(
        0,
        (
            P_component(expr, q, Avec[0], x),
            P_component(expr, q, Avec[1], y),
            P_component(expr, q, Avec[2], z),
        ),
    )


def sigma_P_matrix(mat, q, Avec, coords):
    return simplify_matrix(
        sum(
            (
                SIGMA[n]
                * P_component_matrix(mat, q, Avec[n], coords[n])
                for n in range(3)
            ),
            s.zeros(2),
        )
    )


def apply_E_minus_sigmaP(expr, q, V, Avec, coords):
    t, x, y, z = coords
    return s.expand(E_op(expr, q, V, t) * I2 - sigma_P(expr, q, Avec, (x, y, z)))


def apply_E_plus_sigmaP(expr, q, V, Avec, coords):
    t, x, y, z = coords
    return s.expand(E_op(expr, q, V, t) * I2 + sigma_P(expr, q, Avec, (x, y, z)))


def apply_E_minus_sigmaP_matrix(mat, q, V, Avec, coords):
    t, x, y, z = coords
    return simplify_matrix(E_matrix(mat, q, V, t) - sigma_P_matrix(mat, q, Avec, (x, y, z)))


def apply_E_plus_sigmaP_matrix(mat, q, V, Avec, coords):
    t, x, y, z = coords
    return simplify_matrix(E_matrix(mat, q, V, t) + sigma_P_matrix(mat, q, Avec, (x, y, z)))


def apply_unit_norm(expr, ux, uy, uz):
    return s.simplify(
        s.factor(s.expand(expr)).subs(ux**2 + uy**2 + uz**2, 1)
    )


def matrix_apply_unit_norm(mat, ux, uy, uz):
    return s.Matrix(
        [[apply_unit_norm(entry, ux, uy, uz) for entry in row] for row in mat.tolist()]
    )


