def main():
    results = []

    n, m, k = s.symbols("n m k", integer=True)
    # 1. Sigma product table.
    sigma_ok = True
    for i in range(3):
        for j in range(3):
            lhs = simplify_matrix(SIGMA[i] * SIGMA[j])
            rhs = simplify_matrix(
                (1 if i == j else 0) * I2
                + sum(
                    (
                        s.LeviCivita(i + 1, j + 1, ell + 1) * s.I * SIGMA[ell]
                        for ell in range(3)
                    ),
                    s.zeros(2),
                )
            )
            sigma_ok &= matrix_is_zero(lhs - rhs)
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:basis}--\eqref{eq:sigma-product}",
            "Verified" if sigma_ok else r"\flag{Failed}",
            (
                r"All nine basis products satisfy "
                r"$\sigma_n \sigma_m = \delta_{nm} + \epsilon_{nmk} i \sigma_k$ "
                r"in the Pauli realization."
            ),
        )
    )

    # 2. Dot-cross identity.
    A1, A2, A3, B1, B2, B3 = s.symbols("A1 A2 A3 B1 B2 B3")
    A = (A1, A2, A3)
    B = (B1, B2, B3)
    lhs = simplify_matrix(sigma_dot(A) * sigma_dot(B))
    rhs = simplify_matrix(dot(A, B) * I2 + s.I * sigma_dot(cross(A, B)))
    results.append(
        CheckResult(
            r"Eq.\ \eqref{eq:dot-cross}",
            "Verified" if matrix_is_zero(lhs - rhs) else r"\flag{Failed}",
            (
                r"The product $(\mathbf A\cdot\sigv)(\mathbf B\cdot\sigv)$ reduces to "
                r"$\mathbf A\cdot\mathbf B + i(\mathbf A\times\mathbf B)\cdot\sigv$ "
                r"for symbolic components $A_n,B_n$."
            ),
        )
    )

    # 3. Paravector product and quadratic forms.
    a, b, ap, bp = s.symbols("a b ap bp", real=True)
    Av = s.symbols("Ax Ay Az", real=True)
    Bv = s.symbols("Bx By Bz", real=True)
    Avp = s.symbols("Apx Apy Apz", real=True)
    Bvp = s.symbols("Bpx Bpy Bpz", real=True)
    S = a + s.I * b
    Sp = ap + s.I * bp
    V = tuple(Av[n] + s.I * Bv[n] for n in range(3))
    Vp = tuple(Avp[n] + s.I * Bvp[n] for n in range(3))
    lhs = simplify_matrix(mat_paravector(S, V) * mat_paravector(Sp, Vp))
    rhs = simplify_matrix(
        mat_paravector(
            S * Sp + dot(V, Vp),
            tuple(S * Vp[n] + Sp * V[n] + s.I * cross(V, Vp)[n] for n in range(3)),
        )
    )
    metric_lhs = simplify_matrix(mat_paravector(S, V) * mat_paravector(S, tuple(-vn for vn in V)))
    metric_rhs = simplify_matrix((S**2 - dot(V, V)) * I2)
    euclid_rhs = (a**2 + b**2) + sum(Av[n] ** 2 + Bv[n] ** 2 for n in range(3))
    ZR = mat_paravector(a - s.I * b, tuple(Av[n] - s.I * Bv[n] for n in range(3)))
    euclid_lhs = s.simplify(s.expand(scalar_part(mat_paravector(S, V) * ZR)))
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:paravector-product}--\eqref{eq:minkowski-form}",
            "Verified"
            if matrix_is_zero(lhs - rhs) and matrix_is_zero(metric_lhs - metric_rhs) and s.simplify(euclid_lhs - euclid_rhs) == 0
            else r"\flag{Failed}",
            (
                r"The complex paravector product, the Minkowski-type form "
                r"$Z Z^{*\mathrm R} = S^2 - \mathbf V^2$, and the Euclidean scalar "
                r"part $\operatorname{scalar}(Z Z^{\mathrm R}) = |S|^2 + \|\mathbf V\|^2$ "
                r"all reduce correctly."
            ),
        )
    )

    # 4. Projectors and proper velocity.
    ux, uy, uz = s.symbols("ux uy uz", real=True)
    Udir = sigma_dot((ux, uy, uz))
    Pi_plus = simplify_matrix((I2 + Udir) / 2)
    Pi_minus = simplify_matrix((I2 - Udir) / 2)
    proj_ok = all(
        matrix_is_zero(
            matrix_apply_unit_norm(expr, ux, uy, uz)
        )
        for expr in (
            Pi_plus * Pi_plus - Pi_plus,
            Pi_minus * Pi_minus - Pi_minus,
            Pi_plus * Pi_minus,
            Pi_plus + Pi_minus - I2,
        )
    )
    vx, vy, vz, m0 = s.symbols("vx vy vz m", real=True)
    v2 = vx**2 + vy**2 + vz**2
    gamma = 1 / s.sqrt(1 - v2)
    U = simplify_matrix(mat_paravector(gamma, (gamma * vx, gamma * vy, gamma * vz)))
    U_crev = simplify_matrix(mat_paravector(gamma, (-gamma * vx, -gamma * vy, -gamma * vz)))
    mass_shell = s.simplify(
        s.expand((m0 * gamma) ** 2 - sum((m0 * gamma * comp) ** 2 for comp in (vx, vy, vz)) - m0**2)
    )
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:projectors}, \eqref{eq:proper-velocity}, \eqref{eq:proper-momentum}",
            "Verified"
            if proj_ok and matrix_is_zero(simplify_matrix(U * U_crev - I2)) and mass_shell == 0
            else r"\flag{Failed}",
            (
                r"The idempotents $\Pi(\pm)$ satisfy the projector identities, "
                r"$U U^{*\mathrm R}=1$, and $E^2-\mathbf P^2 = m^2$ follows from "
                r"$mU = E + \mathbf P\cdot\sigv$."
            ),
        )
    )

    # 5. Potential gradient and Maxwell split.
    t, x, y, z, q = s.symbols("t x y z q", real=True)
    Vpot = s.Function("V")(t, x, y, z)
    Avec = tuple(s.Function(name)(t, x, y, z) for name in ("A1", "A2", "A3"))
    gradV = grad_scalar(Vpot, x, y, z)
    divA = div_vector(Avec, x, y, z)
    curlA = curl_vector(Avec, x, y, z)
    partial_phi = simplify_matrix(
        s.diff(Vpot, t) * I2
        + mat_paravector(0, gradV)
        + mat_paravector(0, tuple(s.diff(comp, t) for comp in Avec))
        + divA * I2
        + s.I * sigma_dot(curlA)
    )
    Efield_from_phi = tuple(-s.diff(Avec[n], t) - gradV[n] for n in range(3))
    Bfield_from_phi = curlA
    phi_rhs = simplify_matrix(
        (s.diff(Vpot, t) + divA) * I2
        + mat_paravector(0, tuple(-Efield_from_phi[n] + s.I * Bfield_from_phi[n] for n in range(3)))
    )
    Ex, Ey, Ez = (s.Function(name)(t, x, y, z) for name in ("Ex", "Ey", "Ez"))
    Bx, By, Bz = (s.Function(name)(t, x, y, z) for name in ("Bx", "By", "Bz"))
    Evec = (Ex, Ey, Ez)
    Bvec = (Bx, By, Bz)
    divE = div_vector(Evec, x, y, z)
    divB = div_vector(Bvec, x, y, z)
    curlE = curl_vector(Evec, x, y, z)
    curlB = curl_vector(Bvec, x, y, z)
    partialF = simplify_matrix(
        mat_paravector(0, tuple(s.diff(comp, t) for comp in Evec))
        + s.I * mat_paravector(0, tuple(s.diff(comp, t) for comp in Bvec))
        + divE * I2
        + s.I * sigma_dot(curlE)
        + s.I * divB * I2
        - sigma_dot(curlB)
    )
    maxwell_rhs = simplify_matrix(
        (divE + s.I * divB) * I2
        + sigma_dot(tuple(s.diff(Evec[n], t) - curlB[n] + s.I * (s.diff(Bvec[n], t) + curlE[n]) for n in range(3)))
    )
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:potential-gradient}, \eqref{eq:E-B-from-potential}, \eqref{eq:maxwell}",
            "Verified"
            if matrix_is_zero(partial_phi - phi_rhs) and matrix_is_zero(partialF - maxwell_rhs)
            else r"\flag{Failed}",
            (
                r"The potential identity gives "
                r"$S=\partial_t V+\nabla\cdot\mathbf A$, "
                r"$\mathbf E=-\partial_t\mathbf A-\nabla V$, and "
                r"$\mathbf B=\nabla\times\mathbf A$, while $\partial F$ splits into "
                r"Gauss, Faraday, and Amp\`ere--Maxwell component equations with the manuscript's signs."
            ),
        )
    )

    # 6. Gauge invariance and Lorentz force split.
    lam = s.Function("lambda")(t, x, y, z)
    grad_lam = grad_scalar(lam, x, y, z)
    gauge_phi = simplify_matrix(
        mat_paravector(Vpot + s.diff(lam, t), tuple(Avec[n] - grad_lam[n] for n in range(3)))
    )
    gauge_expected = simplify_matrix(
        mat_paravector(Vpot, Avec) + mat_paravector(s.diff(lam, t), tuple(-grad_lam[n] for n in range(3)))
    )
    Fx, Fy, Fz, Gx, Gy, Gz = s.symbols("Fx Fy Fz Gx Gy Gz", real=True)
    Etest = (Fx, Fy, Fz)
    Btest = (Gx, Gy, Gz)
    Fmat = mat_paravector(0, tuple(Etest[n] + s.I * Btest[n] for n in range(3)))
    Utest = mat_paravector(gamma, (gamma * vx, gamma * vy, gamma * vz))
    FU = simplify_matrix(Fmat * Utest)
    expected_real = simplify_matrix(
        dot(Etest, (vx, vy, vz)) * gamma * I2
        + sigma_dot(
            tuple(
                gamma * (Etest[n] + cross((vx, vy, vz), Btest)[n])
                for n in range(3)
            )
        )
    )
    real_part = simplify_matrix((FU + FU.conjugate().xreplace({s.I: -s.I})) / 2)
    # Extract the STA-real sector explicitly from the known decomposition.
    fu_decomp = simplify_matrix(
        expected_real
        + s.I * (
            dot(Btest, (vx, vy, vz)) * gamma * I2
            + sigma_dot(
                tuple(
                    gamma * (Btest[n] + cross(Etest, (vx, vy, vz))[n])
                    for n in range(3)
                )
            )
        )
    )
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:gauge} and \eqref{eq:lorentz-force}",
            "Verified"
            if matrix_is_zero(gauge_phi - gauge_expected) and matrix_is_zero(FU - fu_decomp)
            else r"\flag{Failed}",
            (
                r"The gauge law $\Phi'=\Phi+\partial^{*}\lambda$ gives "
                r"$V' = V+\partial_t\lambda$ and $\mathbf A' = \mathbf A-\nabla\lambda$, "
                r"and the product $FU$ splits into the expected power term "
                r"$\gamma\,\mathbf v\cdot\mathbf E$ and force term "
                r"$\gamma(\mathbf E+\mathbf v\times\mathbf B)$."
            ),
        )
    )

    # 7. Minimal coupling, commutators, and factorization.
    psi = s.Function("psi")(t, x, y, z)
    kg_expr = s.simplify(
        s.expand(
            -E_op(E_op(psi, q, Vpot, t), q, Vpot, t)
            + sum(
                P_component(P_component(psi, q, Avec[n], coord), q, Avec[n], coord)
                for n, coord in enumerate((x, y, z))
            )
        )
    )
    S_scalar = s.diff(Vpot, t) + divA
    minkowski_phi = Vpot**2 - dot(Avec, Avec)
    kg_expected = s.simplify(
        s.expand(
            s.diff(psi, t, 2)
            - s.diff(psi, x, 2)
            - s.diff(psi, y, 2)
            - s.diff(psi, z, 2)
            + s.I * q * S_scalar * psi
            - q**2 * minkowski_phi * psi
            + 2 * s.I * q * (Vpot * s.diff(psi, t) + sum(Avec[n] * s.diff(psi, coord) for n, coord in enumerate((x, y, z))))
        )
    )
    Em = tuple(-s.diff(Vpot, coord) - s.diff(Avec[n], t) for n, coord in enumerate((x, y, z)))
    Bm = curlA
    comm_EPm = []
    for idx, coord in enumerate((x, y, z)):
        lhs_comm = s.simplify(
            s.expand(E_op(P_component(psi, q, Avec[idx], coord), q, Vpot, t) - P_component(E_op(psi, q, Vpot, t), q, Avec[idx], coord))
        )
        rhs_comm = s.simplify(s.expand(s.I * q * Em[idx] * psi))
        comm_EPm.append(lhs_comm - rhs_comm)
    comm_P = []
    for a_idx, coord_a in enumerate((x, y, z)):
        for b_idx, coord_b in enumerate((x, y, z)):
            lhs_comm = s.simplify(
                s.expand(
                    P_component(P_component(psi, q, Avec[b_idx], coord_b), q, Avec[a_idx], coord_a)
                    - P_component(P_component(psi, q, Avec[a_idx], coord_a), q, Avec[b_idx], coord_b)
                )
            )
            rhs_comm = s.simplify(
                s.expand(
                    s.I * q * (s.diff(Avec[b_idx], coord_a) - s.diff(Avec[a_idx], coord_b)) * psi
                )
            )
            comm_P.append(lhs_comm - rhs_comm)
    right_factor = apply_E_minus_sigmaP(psi, q, Vpot, Avec, (t, x, y, z))
    factor_lhs = apply_E_plus_sigmaP_matrix(right_factor, q, Vpot, Avec, (t, x, y, z))
    factor_rhs = simplify_matrix(
        (E_op(E_op(psi, q, Vpot, t), q, Vpot, t)
         - sum(P_component(P_component(psi, q, Avec[n], coord), q, Avec[n], coord) for n, coord in enumerate((x, y, z)))) * I2
        - s.I * q * sigma_dot(tuple(Em[n] + s.I * Bm[n] for n in range(3))) * psi
    )
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:kg-expanded}, \eqref{eq:commutators}, and \eqref{eq:EP-factorization}",
            "Verified"
            if s.simplify(kg_expr - kg_expected) == 0
            and all(s.simplify(expr) == 0 for expr in comm_EPm)
            and all(s.simplify(expr) == 0 for expr in comm_P)
            and matrix_is_zero(factor_lhs - factor_rhs)
            else r"\flag{Failed}",
            (
                r"Acting on a generic test function reproduces the expanded Klein--Gordon "
                r"operator, the commutators $[E,P_m]=iqE_m$ and "
                r"$[P_m,P_n]=iq(\partial_mA_n-\partial_nA_m)$, and the factorization "
                r"$(E+\sigv\cdot\mathbf P)(E-\sigv\cdot\mathbf P)=E^2-\mathbf P^2-iqF$."
            ),
        )
    )

    # 8. Frequency split, Dirac square, Pauli operator, and spin split.
    uB = (ux, uy, uz)
    B0 = s.symbols("B0", real=True)
    Buniform = tuple(B0 * comp for comp in uB)
    psi1 = s.Function("psi1")(t, x, y, z)
    psi2 = s.Function("psi2")(t, x, y, z)
    dirac_upper = simplify_matrix(
        apply_E_minus_sigmaP_matrix(
            apply_E_plus_sigmaP(psi1, q, Vpot, Avec, (t, x, y, z)),
            q,
            Vpot,
            Avec,
            (t, x, y, z),
        )
    )
    dirac_upper_rhs = simplify_matrix(
        (
            E_op(E_op(psi1, q, Vpot, t), q, Vpot, t)
            - sum(P_component(P_component(psi1, q, Avec[n], coord), q, Avec[n], coord) for n, coord in enumerate((x, y, z)))
        ) * I2
        + s.I * q * sigma_dot(tuple(Em[n] - s.I * Bm[n] for n in range(3))) * psi1
    )
    dirac_lower = simplify_matrix(
        apply_E_plus_sigmaP_matrix(
            apply_E_minus_sigmaP(psi2, q, Vpot, Avec, (t, x, y, z)),
            q,
            Vpot,
            Avec,
            (t, x, y, z),
        )
    )
    dirac_lower_rhs = simplify_matrix(
        (
            E_op(E_op(psi2, q, Vpot, t), q, Vpot, t)
            - sum(P_component(P_component(psi2, q, Avec[n], coord), q, Avec[n], coord) for n, coord in enumerate((x, y, z)))
        ) * I2
        - s.I * q * sigma_dot(tuple(Em[n] + s.I * Bm[n] for n in range(3))) * psi2
    )
    spin_split_ok = all(
        matrix_is_zero(
            matrix_apply_unit_norm(
                sigma_dot(Buniform) * Pi_plus - B0 * Pi_plus,
                ux,
                uy,
                uz,
            )
        )
        for _ in [0]
    ) and matrix_is_zero(
        matrix_apply_unit_norm(
            sigma_dot(Buniform) * Pi_minus + B0 * Pi_minus,
            ux,
            uy,
            uz,
        )
    )
    sigmaP_squared = simplify_matrix(
        sigma_P_matrix(
            sigma_P(psi, q, Avec, (x, y, z)),
            q,
            Avec,
            (x, y, z),
        )
    )
    pauli_expected = simplify_matrix(
        sum(P_component(P_component(psi, q, Avec[n], coord), q, Avec[n], coord) for n, coord in enumerate((x, y, z))) * I2
        - q * sigma_dot(Bm) * psi
    )
    results.append(
        CheckResult(
            r"Eqs.\ \eqref{eq:dirac-square}, \eqref{eq:pauli-operator}, and \eqref{eq:pauli-spin-split}",
            "Verified"
            if matrix_is_zero(dirac_upper - dirac_upper_rhs)
            and matrix_is_zero(dirac_lower - dirac_lower_rhs)
            and matrix_is_zero(sigmaP_squared - pauli_expected)
            and spin_split_ok
            else r"\flag{Failed}",
            (
                r"Eliminating one Dirac component yields the two squared equations; with the manuscript's "
                r"operator ordering, the upper component carries $-iqF^{*}$ after everything is moved to "
                r"the left-hand side, while the lower component carries $+iqF$. The exact Pauli identity "
                r"$(\sigv\cdot\mathbf P)^2 = \mathbf P^2 - q\,\mathbf B\cdot\sigv$ "
                r"holds on a test function; and for uniform $\mathbf B = B_0 \mathbf u$ "
                r"the projectors satisfy $(\mathbf B\cdot\sigv)\Pi(\pm)=\pm B_0 \Pi(\pm)$."
            ),
        )
    )

    # 9. Quaternion square.
    qa, bx, by, bz = s.symbols("qa bx by bz", real=True)
    qmat = simplify_matrix(qa * I2 - s.I * sigma_dot((bx, by, bz)))
    qlhs = simplify_matrix(qmat * qmat)
    qrhs = simplify_matrix((qa**2 - bx**2 - by**2 - bz**2) * I2 - 2 * s.I * qa * sigma_dot((bx, by, bz)))
    qnorm = simplify_matrix(qmat * (qa * I2 + s.I * sigma_dot((bx, by, bz))) - (qa**2 + bx**2 + by**2 + bz**2) * I2)
    results.append(
        CheckResult(
            r"Eq.\ \eqref{eq:quaternion-square}",
            "Verified" if matrix_is_zero(qlhs - qrhs) and matrix_is_zero(qnorm) else r"\flag{Failed}",
            (
                r"The quaternion correspondence satisfies "
                r"$QQ^{\mathsf R}=a^2+\mathbf b^2$ and "
                r"$Q^2=a^2-\mathbf b^2-2ia\,\mathbf b\cdot\sigv$; the omitted factor of $a$ "
                r"in the older intermediate line is indeed an error."
            ),
        )
    )

    write_report(results)


